import React from 'react';
import { User } from '../types';
import { store } from '../store/sheffieldStore';
import { PageHead, StatusBadge, EmptyState } from '../components/CommonUI';

interface IntegrationsViewProps {
  user: User;
  onToast: (msg: string, isError?: boolean) => void;
}

export const IntegrationsView: React.FC<IntegrationsViewProps> = ({ user, onToast }) => {
  const { systems, events } = store.getIntegrations(user);
  const isAdmin = user.role === 'admin';

  const handleProcess = (id: number, simulateFail: boolean) => {
    try {
      const res = store.processIntegration(id, simulateFail, user);
      if (simulateFail) {
        onToast('Simulated integration timeout captured');
      } else {
        onToast(`Mock adapter: ${res.status}`);
      }
    } catch (err: any) {
      onToast(err.message, true);
    }
  };

  return (
    <div>
      <PageHead
        title="Integration & recovery console"
        kicker="MOCK ADAPTER / AUDITABLE EXCEPTIONS"
        desc="See controlled integration events, simulate a failure and retry with exactly-once local event identifiers."
      />

      <div className="note attention">
        These adapters are local mocks. Entra ID/MFA, Outlook, corporate finance, CRM and payment providers have not
        been connected. A green Delivered status here means the mock adapter acknowledged the event, not the actual
        external system.
      </div>

      <div className="grid three" style={{ marginTop: 16 }}>
        {systems.map((s) => (
          <div key={s.id} className="card tight">
            <span className="badge blue">{s.method}</span>
            <h3 style={{ marginTop: 10 }}>{s.name}</h3>
            <p className="small muted">{s.description}</p>
          </div>
        ))}
      </div>

      <div className="card" style={{ marginTop: 20 }}>
        <div className="section-top">
          <h2>Integration event queue</h2>
          <span>Force failure then retry successfully</span>
        </div>

        <div className="table-scroll">
          <table className="data-table">
            <thead>
              <tr>
                <th>System / event</th>
                <th>Entity</th>
                <th>Attempts</th>
                <th>State</th>
                <th>Latest exception</th>
                <th>Action</th>
              </tr>
            </thead>
            <tbody>
              {events.length ? (
                events.map((e) => (
                  <tr key={e.id}>
                    <td>
                      <strong>{e.system}</strong>
                      <div className="micro muted">{e.event}</div>
                    </td>
                    <td>#{e.entity_id}</td>
                    <td>{e.attempts}</td>
                    <td>
                      <StatusBadge value={e.status} />
                    </td>
                    <td>{e.error || '--'}</td>
                    <td>
                      {e.status !== 'Delivered' && isAdmin ? (
                        <span className="inline-actions">
                          <button
                            className="btn light small"
                            onClick={() => handleProcess(e.id, false)}
                            type="button"
                          >
                            Process
                          </button>
                          <button
                            className="btn danger small"
                            onClick={() => handleProcess(e.id, true)}
                            type="button"
                          >
                            Inject failure
                          </button>
                        </span>
                      ) : (
                        '--'
                      )}
                    </td>
                  </tr>
                ))
              ) : (
                <tr>
                  <td colSpan={6}>
                    <EmptyState message="No integration events queued yet. Staged events are generated by onboarding, approved timesheets, and finalised payroll." />
                  </td>
                </tr>
              )}
            </tbody>
          </table>
        </div>
      </div>
    </div>
  );
};
